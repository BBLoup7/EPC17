/**
 * Crash-Proof Event Snapshot Generator
 * Produces a complete, printable HTML snapshot of event state including:
 *   - Event details (name, date, location, series, settings)
 *   - Registered participants per class
 *   - All bracket rounds, heats, results, and lane assignments
 *   - Current standings per class
 * 
 * Can auto-print after each round or class completion.
 *
 * @module event-snapshot
 * Exports: window.EventSnapshot
 *
 * Usage:
 *   const snapshot = new EventSnapshot(dataManager, raceManager);
 *   snapshot.generateAndPrint(eventId);               // manual
 *   snapshot.setAutoPrint(eventId, 'round');           // auto-print after each round
 */

class EventSnapshot {
    constructor(dataManager, raceManager) {
        this.dataManager = dataManager;
        this.raceManager = raceManager;
        this._autoPrintMode = null; // 'round' | 'class' | null
        this._autoPrintEventId = null;
    }

    /**
     * Configure auto-print mode.
     * @param {string} eventId
     * @param {'round'|'class'|null} mode - When to auto-print
     */
    setAutoPrint(eventId, mode) {
        this._autoPrintEventId = eventId;
        this._autoPrintMode = mode;

        // Subscribe to bracket events
        if (mode && window.globalEventBus) {
            window.globalEventBus.on('bracket:updated', (data) => {
                if (data.eventId !== eventId) return;
                if (mode === 'round' || mode === 'class') {
                    this.generateAndPrint(eventId);
                }
            });
        }
        window.debugLogger?.debug('Snapshot', `Auto-print ${mode ? 'enabled' : 'disabled'} for event ${eventId}`);
    }

    /**
     * Generate the snapshot HTML and open it in a print-ready window.
     * @param {string} eventId
     */
    async generateAndPrint(eventId) {
        const html = await this.generateSnapshotHtml(eventId);
        if (!html) return;

        const printWindow = window.open('', '_blank', 'width=900,height=700');
        if (!printWindow) {
            console.error('Popup blocked — cannot open print window');
            return;
        }
        printWindow.document.write(html);
        printWindow.document.close();
        printWindow.focus();
        setTimeout(() => printWindow.print(), 500);
    }

    /**
     * Generate the full snapshot HTML document.
     * @param {string} eventId
     * @returns {string} Complete HTML document
     */
    async generateSnapshotHtml(eventId) {
        const event = this.dataManager.getEvent(eventId);
        if (!event) return null;

        const bracket = await this.raceManager.getBracket(eventId);
        const series = event.seriesId ? this.dataManager.getSeries(event.seriesId) : null;
        const participants = this.dataManager.getParticipantsByEvent?.(eventId) || [];

        const now = new Date().toLocaleString();

        return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>Event Snapshot — ${this._esc(event.name)}</title>
<style>
  @page { margin: 0.5in; }
  * { box-sizing: border-box; margin: 0; padding: 0; }
  body { font-family: 'Segoe UI', sans-serif; font-size: 11px; color: #111; line-height: 1.4; }
  h1 { font-size: 18px; margin-bottom: 4px; }
  h2 { font-size: 14px; margin: 12px 0 6px; border-bottom: 1px solid #333; padding-bottom: 2px; }
  h3 { font-size: 12px; margin: 8px 0 4px; }
  table { width: 100%; border-collapse: collapse; margin-bottom: 8px; }
  th, td { border: 1px solid #888; padding: 3px 6px; text-align: left; font-size: 10px; }
  th { background: #ddd; font-weight: 600; }
  .meta { color: #555; font-size: 10px; margin-bottom: 10px; }
  .heat-completed { background: #e8f5e9; }
  .heat-pending { background: #fff3e0; }
  .badge { display: inline-block; padding: 1px 5px; border-radius: 3px; font-size: 9px; font-weight: 600; }
  .badge-win { background: #c8e6c9; color: #2e7d32; }
  .badge-loss { background: #ffcdd2; color: #c62828; }
  .badge-elim { background: #f5f5f5; color: #616161; }
  .page-break { page-break-after: always; }
  .footer { margin-top: 16px; font-size: 9px; color: #999; text-align: center; }
</style>
</head>
<body>
<h1>${this._esc(event.name)}</h1>
<div class="meta">
  ${this._esc(event.location || '')} | ${event.date ? new Date(event.date).toLocaleDateString() : '—'} | 
  Series: ${this._esc(series?.name || '—')} | 
  Elimination: ${this._esc(event.eliminationType || 'double')} | 
  Lanes: ${event.numberOfTracks || 3} | 
  Snapshot: ${now}
</div>

${this._renderParticipantsSection(participants, event)}

${bracket ? this._renderBracketSection(bracket, event) : '<p>No bracket data available.</p>'}

<div class="footer">
  Crash-proof snapshot generated by EPC17 — ${now}
</div>
</body>
</html>`;
    }

    // ---- Internal renderers ----

    _renderParticipantsSection(participants, event) {
        if (!participants.length) return '<h2>Participants</h2><p>No participants registered.</p>';

        // Group by class
        const byClass = {};
        participants.forEach(p => {
            const classes = p.selectedClasses || p.eventClasses || ['Unclassed'];
            (Array.isArray(classes) ? classes : [classes]).forEach(c => {
                if (!byClass[c]) byClass[c] = [];
                byClass[c].push(p);
            });
        });

        let html = '<h2>Registered Participants</h2>';
        for (const [className, group] of Object.entries(byClass)) {
            html += `<h3>${this._esc(className)} (${group.length} drivers)</h3>`;
            html += '<table><tr><th>#</th><th>Name</th><th>Racing #</th><th>Status</th></tr>';
            group.forEach((p, i) => {
                html += `<tr><td>${i + 1}</td><td>${this._esc(p.name)}</td><td>${this._esc(p.racingNumber || '—')}</td><td>${this._esc(p.status || 'active')}</td></tr>`;
            });
            html += '</table>';
        }
        return html;
    }

    _renderBracketSection(bracket, event) {
        if (!bracket.classes) return '';
        let html = '<h2>Race Brackets</h2>';

        for (const [className, classBracket] of Object.entries(bracket.classes)) {
            html += `<h3>${this._esc(className)} ${classBracket.isComplete ? '✓ COMPLETE' : ''}</h3>`;

            (classBracket.rounds || []).forEach(round => {
                const label = round.roundNumber === 'final' ? 'Final' :
                              round.type === 'tie_breaker' ? 'Tie-Breaker' :
                              `Round ${round.roundNumber}`;
                html += `<h3>${label} ${round.isComplete ? '✓' : ''}</h3>`;
                html += '<table><tr><th>Race#</th><th>Status</th>';

                const maxLanes = Math.max(...(round.heats || []).map(h => (h.lanes || []).length), 3);
                for (let l = 1; l <= maxLanes; l++) html += `<th>Lane ${l}</th>`;
                html += '<th>Results</th></tr>';

                (round.heats || []).forEach(heat => {
                    const rowClass = heat.status === 'completed' ? 'heat-completed' : 'heat-pending';
                    html += `<tr class="${rowClass}">`;
                    html += `<td>${heat.raceNumber || '—'}</td>`;
                    html += `<td>${heat.status || 'pending'}</td>`;

                    const lanes = heat.lanes || [];
                    for (let l = 0; l < maxLanes; l++) {
                        const lane = lanes[l];
                        const name = lane?.participant?.name || lane?.participantName || '—';
                        html += `<td>${this._esc(name)}</td>`;
                    }

                    // Results
                    if (heat.results && heat.results.length) {
                        const resultStr = heat.results
                            .sort((a, b) => (a.position || 99) - (b.position || 99))
                            .map(r => {
                                const name = lanes.find(l => (l.participant?.id || l.participantId) === r.participantId)?.participant?.name || r.participantId?.substring(0, 8);
                                return `${r.position}. ${this._esc(name)}`;
                            }).join(', ');
                        html += `<td>${resultStr}</td>`;
                    } else {
                        html += '<td>—</td>';
                    }
                    html += '</tr>';
                });
                html += '</table>';
            });

            // Standings for this class
            if (classBracket.participants && classBracket.participants.length > 0) {
                html += `<h3>Standings — ${this._esc(className)}</h3>`;
                html += '<table><tr><th>#</th><th>Name</th><th>W</th><th>L</th><th>Status</th><th>Bracket</th></tr>';
                const sorted = [...classBracket.participants].sort((a, b) => (b.wins || 0) - (a.wins || 0) || (a.losses || 0) - (b.losses || 0));
                sorted.forEach((p, i) => {
                    const status = p.status === 'eliminated' ? '<span class="badge badge-elim">ELIM</span>' :
                                   p.status === 'active' ? '<span class="badge badge-win">ACTIVE</span>' : p.status || '—';
                    html += `<tr><td>${i + 1}</td><td>${this._esc(p.name)}</td><td>${p.wins || 0}</td><td>${p.losses || 0}</td><td>${status}</td><td>${this._esc(p.currentBracket || '—')}</td></tr>`;
                });
                html += '</table>';
            }
        }
        return html;
    }

    _esc(str) {
        if (!str) return '';
        return String(str).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
    }
}

// Global export
if (typeof window !== 'undefined') {
    window.EventSnapshot = EventSnapshot;
}

if (typeof module !== 'undefined' && module.exports) {
    module.exports = EventSnapshot;
}
